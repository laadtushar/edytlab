// Compaction — trading history for disk, deliberately (#98 option b)
// =============================================================================

/// What a compaction would remove, computed before anything is touched
/// so the tool can describe it and then do exactly that.
#[derive(Debug, Clone, Default)]
pub struct CompactionPlan {
    /// Nodes to delete, in an order safe to apply: never a node that
    /// something still kept parents off.
    pub nodes: Vec<session::NodeId>,
    /// The oldest node that survives on the head's chain. Its parent
    /// link is cut when the plan is applied, so the kept history ends
    /// cleanly instead of pointing at something deleted.
    pub new_root: Option<session::NodeId>,
    /// Files only those nodes reference, and their total size.
    pub files: Vec<PathBuf>,
    pub bytes: u64,
    pub total_nodes: usize,
}

/// What a compaction actually did.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CompactionReport {
    pub removed_nodes: usize,
    pub removed_files: usize,
    pub freed_bytes: u64,
}

/// The head's chain, newest first.
fn chain_from(store: &session::Store, head: session::NodeId) -> Vec<session::NodeId> {
    let mut out = Vec::new();
    let mut cursor = Some(head);
    while let Some(id) = cursor {
        let Ok(node) = store.get(id) else { break };
        out.push(id);
        cursor = node.parent;
    }
    out
}

/// Work out what a compaction would remove.
///
/// Two things go: the tail of the head's chain beyond `keep_last`, and
/// anything not on the chain at all — branches forked away from and
/// never returned to.
///
/// The tail is kept *contiguous*. Removing a node from the middle of
/// the chain would strand everything below it, because a walk from the
/// head follows parent links and stops at the first gap. So the cut is
/// always "everything older than the Nth", never a set of individually
/// chosen nodes.
pub fn plan_compaction(
    store: &session::Store,
    head: session::NodeId,
    keep_last: usize,
) -> Result<CompactionPlan, String> {
    let all = store
        .list_nodes()
        .map_err(|e| format!("failed to list nodes: {e}"))?;
    let chain = chain_from(store, head);
    let chain_set: HashSet<_> = chain.iter().copied().collect();

    let mut doomed: Vec<session::NodeId> = Vec::new();
    let mut new_root = None;
    // The tail of the chain, oldest first so removal never orphans a
    // node that is still kept.
    if chain.len() > keep_last {
        doomed.extend(chain[keep_last..].iter().rev().copied());
        // The last one kept becomes a root; without this its parent
        // link dangles and walking back reads as a corrupt store.
        new_root = chain.get(keep_last - 1).copied();
    }
    // Everything off the chain entirely.
    for node in &all {
        if !chain_set.contains(&node.id) {
            doomed.push(node.id);
        }
    }

    // Which files survive: named by any node that is *not* being
    // removed. A file is only reclaimable when nothing kept wants it.
    let doomed_set: HashSet<_> = doomed.iter().copied().collect();
    let mut kept_refs: BTreeSet<PathBuf> = BTreeSet::new();
    let mut doomed_refs: BTreeSet<PathBuf> = BTreeSet::new();
    for node in &all {
        let target = if doomed_set.contains(&node.id) {
            &mut doomed_refs
        } else {
            &mut kept_refs
        };
        for track in &node.state.tracks {
            for clip in &track.clips {
                target.insert(key(&clip.source_path));
            }
        }
    }

    let mut files = Vec::new();
    let mut bytes = 0u64;
    for path in doomed_refs.difference(&kept_refs) {
        if let Ok(meta) = std::fs::metadata(path) {
            bytes += meta.len();
            files.push(path.clone());
        }
    }

    Ok(CompactionPlan {
        nodes: doomed,
        new_root,
        files,
        bytes,
        total_nodes: all.len(),
    })
}

/// Carry out a plan.
///
/// Nodes first, audio second. A compaction interrupted between the two
/// leaves a session whose history is shorter and whose audio is intact
/// — which still works. The other order would leave nodes pointing at
/// files that are gone.
pub fn apply_compaction(
    store: &mut session::Store,
    plan: &CompactionPlan,
) -> Result<CompactionReport, String> {
    let mut report = CompactionReport::default();

    for id in &plan.nodes {
        match store.remove_node(*id) {
            Ok(true) => report.removed_nodes += 1,
            Ok(false) => {}
            Err(e) => return Err(format!("failed to remove node {}: {e}", id.to_hex())),
        }
    }

    // Cut the dangling link before the audio goes, so an interruption
    // still leaves a walkable chain.
    if let Some(root) = plan.new_root {
        store
            .detach_parent(root)
            .map_err(|e| format!("failed to make {} a root: {e}", root.to_hex()))?;
    }

    for path in &plan.files {
        if let Ok(meta) = std::fs::metadata(path) {
            if std::fs::remove_file(path).is_ok() {
                report.removed_files += 1;
                report.freed_bytes += meta.len();
            }
        }
    }

    Ok(report)
}
