/** Copy the actual CLI and path policy into a synthetic repository with brand inputs. */
function fixture(t: TestContext) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'promo-tokens-')));
  t.after(() => {
    rmSync(root, {recursive: true, force: true});
  });
  const promo = join(root, 'marketing/promo-v0.7.0');
  const remotion = join(promo, 'remotion');
  const scripts = join(remotion, 'scripts');
  const outside = join(root, 'outside');
  for (const dir of [scripts, join(remotion, 'src'), join(promo, 'record'),
    join(root, 'website/app'), join(root, 'website/public'), outside]) {
    mkdirSync(dir, {recursive: true});
  }
  writeFileSync(join(root, 'package.json'), '{"type":"module"}');
  writeFileSync(join(root, 'website/app/globals.css'), CSS);
  writeFileSync(join(root, 'website/public/logo.svg'), LOGO);
  for (const name of ['tokens.ts', 'paths.ts']) {
    copyFileSync(join(SCRIPTS, name), join(scripts, name));
  }
  copyFileSync(join(SOURCE_PROMO, 'record/paths.mjs'), join(promo, 'record/paths.mjs'));
  return {promo, remotion, outside, output: join(remotion, 'src/tokens.generated.ts')};
}

/** Execute the real standalone token CLI using only the synthetic repository. */
function run(remotion: string, check = false) {
  return spawnSync(process.execPath, ['scripts/tokens.ts', ...(check ? ['--check'] : [])], {
    cwd: remotion, encoding: 'utf8',
  });
}

/** Record the outside directory's names and bytes to detect unintended output I/O. */
function outsideFiles(directory: string) {
  return readdirSync(directory).sort().map((name) => [name, readFileSync(join(directory, name)).toString('hex')]);
}

await test('tokens write exact original bytes and preserve current/stale check behavior', (t) => {
  const {remotion, output} = fixture(t);
  const missing = run(remotion, true);
  assert.equal(missing.status, 1);
  assert.match(missing.stderr, /out of date/);
  assert.equal(existsSync(output), false);
  const generated = run(remotion);
  assert.equal(generated.status, 0, generated.stderr);
  assert.equal(readFileSync(output, 'utf8'), GOLDEN);
  assert.ok(generated.stdout.startsWith(`wrote ${output} `));
  const checked = run(remotion, true);
  assert.equal(checked.status, 0, checked.stderr);
  assert.ok(checked.stdout.startsWith('tokens ok '));
  assert.equal(readFileSync(output, 'utf8'), GOLDEN);
  writeFileSync(output, 'stale local tokens');
  const stale = run(remotion, true);
  assert.equal(stale.status, 1);
  assert.match(stale.stderr, /out of date/);
  assert.equal(readFileSync(output, 'utf8'), 'stale local tokens');
});

for (const kind of ['existing leaf', 'dangling leaf', 'parent']) {
  await test(`tokens preserve valid internal ${kind} symlink output`, (t) => {
    const {promo, remotion, output} = fixture(t);
    const targetDirectory = join(promo, 'local-token-output');
    mkdirSync(targetDirectory);
    const target = join(targetDirectory, 'tokens.generated.ts');
    if (kind === 'parent') {
      rmSync(dirname(output), {recursive: true});
      symlinkSync(targetDirectory, dirname(output));
    } else {
      if (kind === 'existing leaf') writeFileSync(target, 'old tokens');
      symlinkSync(target, output);
    }
    const generated = run(remotion);
    assert.equal(generated.status, 0, generated.stderr);
    assert.equal(readFileSync(target, 'utf8'), GOLDEN);
    assert.ok(generated.stdout.startsWith(`wrote ${output} `));
    assert.equal(lstatSync(kind === 'parent' ? dirname(output) : output).isSymbolicLink(), true);
    const checked = run(remotion, true);
    assert.equal(checked.status, 0, checked.stderr);
    assert.equal(readFileSync(target, 'utf8'), GOLDEN);
  });
}

for (const kind of ['existing leaf', 'dangling leaf', 'existing parent', 'dangling parent']) {
  for (const check of [false, true]) {
    await test(`tokens ${check ? '--check' : 'write'} refuses outside ${kind} symlink`, (t) => {
      const {promo, remotion, outside, output} = fixture(t);
      const parent = kind.endsWith('parent');
      const dangling = kind.startsWith('dangling');
      const targetDirectory = parent && dangling ? join(outside, 'missing') : outside;
      const target = join(targetDirectory, 'tokens.generated.ts');
      if (!dangling) writeFileSync(target, check ? GOLDEN : 'outside sentinel');
      if (parent) {
        rmSync(dirname(output), {recursive: true});
        symlinkSync(targetDirectory, dirname(output));
      } else {
        symlinkSync(target, output);
      }
      const before = outsideFiles(outside);
      const refused = run(remotion, check);
      assert.notEqual(refused.status, 0);
      assert.ok(refused.stderr.includes('Refused path'), refused.stderr);
      assert.ok(refused.stderr.includes(promo), refused.stderr);
      assert.ok(refused.stderr.includes(JSON.stringify(output)), refused.stderr);
      assert.deepEqual(outsideFiles(outside), before);
      if (dangling) assert.equal(existsSync(target), false);
    });
  }
}
