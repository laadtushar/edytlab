// Writes src/tokens.generated.ts from the website's own files, the way marketing/reels/tools/brand.py reads them,
// so the edit's colours are never typed in by eye:
//   website/app/globals.css   the `.dark` token block (the site is dark by default), --radius, `.gradient-text`, `.aurora`
//   website/public/logo.svg   the mark's two fills
// `node scripts/tokens.ts`          rewrite the file
// `node scripts/tokens.ts --check`  fail if the file on disk is not what the site's files give now (a palette change on
//                                   the site cannot slip into the edit unnoticed), and fail if a text colour on its
//                                   own fill is under 4.5:1 contrast.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../../../..');
const CSS = readFileSync(resolve(REPO, 'website/app/globals.css'), 'utf8');
const LOGO = readFileSync(resolve(REPO, 'website/public/logo.svg'), 'utf8');
const OUT = resolve(HERE, '../src/tokens.generated.ts');

type RGB = [number, number, number];

function hsl(h: number, s: number, l: number): RGB {
  s /= 100;
  l /= 100;
  const c = (1 - Math.abs(2 * l - 1)) * s;
  const hp = (((h % 360) + 360) % 360) / 60;
  const x = c * (1 - Math.abs((hp % 2) - 1));
  const table: RGB[] = [[c, x, 0], [x, c, 0], [0, c, x], [0, x, c], [x, 0, c], [c, 0, x]];
  const [r, g, b] = table[Math.floor(hp) % 6];
  const m = l - c / 2;
  return [r, g, b].map((v) => Math.floor((v + m) * 255 + 0.5)) as RGB;
}

const hex = (c: RGB) => '#' + c.map((v) => v.toString(16).padStart(2, '0')).join('');

/** The body of the first `selector { ... }` rule, braces matched. */
function rule(selector: string): string {
  const start = CSS.indexOf(selector + ' {');
  if (start < 0) throw new Error(`${selector} not found in globals.css`);
  const open = CSS.indexOf('{', start);
  let depth = 0;
  for (let i = open; i < CSS.length; i++) {
    if (CSS[i] === '{') depth++;
    if (CSS[i] === '}') depth--;
    if (depth === 0) return CSS.slice(open + 1, i);
  }
  throw new Error(`unbalanced braces after ${selector}`);
}

function token(block: string, name: string): RGB {
  const m = new RegExp(`--${name}:\\s*([\\d.]+)\\s+([\\d.]+)%\\s+([\\d.]+)%`).exec(block);
  if (!m) throw new Error(`--${name} not found in the site's .dark block`);
  return hsl(+m[1], +m[2], +m[3]);
}

function hsls(text: string): RGB[] {
  return [...text.matchAll(/hsl\(\s*([\d.]+)\s+([\d.]+)%\s+([\d.]+)%\s*\)/g)].map((m) => hsl(+m[1], +m[2], +m[3]));
}

const dark = rule('.dark');
const background = token(dark, 'background');
const card = token(dark, 'card');
const foreground = token(dark, 'foreground');
const primary = token(dark, 'primary');
const mutedForeground = token(dark, 'muted-foreground');
const border = token(dark, 'border');
const radiusPx = Math.round(parseFloat(/--radius:\s*([\d.]+)rem/.exec(CSS)![1]) * 16);
const gradient = hsls(rule('.gradient-text')).slice(0, 2);
const aurora = hsls(CSS.slice(CSS.indexOf('.aurora::before {'))).slice(0, 2);
const auroraOpacity = parseFloat(/opacity:\s*([\d.]+)/.exec(rule('.aurora::before,\n  .aurora::after'))![1]);
const fills = [...new Set([...LOGO.matchAll(/(?:fill|stroke)="#([0-9A-Fa-f]{6})"/g)].map((m) => '#' + m[1].toUpperCase()))];
if (fills.length !== 2) throw new Error(`expected two colours in website/public/logo.svg, found ${fills}`);

// ---------------------------------------------------------------- contrast (WCAG 2)
const lin = (c: number) => ((c /= 255) <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = ([r, g, b]: RGB) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
const contrast = (a: RGB, b: RGB) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const pairs: Record<string, [RGB, RGB]> = {
  'title on background': [foreground, background],
  'caption on card': [foreground, card],
  'accent on card': [primary, card],
  'note on background': [mutedForeground, background],
  'note on card': [mutedForeground, card],
  'gradient start on background': [gradient[0], background],
  'gradient end on background': [gradient[1], background],
  'url on background': [primary, background],
};
const contrasts: Record<string, number> = {};
for (const [name, [fg, bg]] of Object.entries(pairs)) {
  const ratio = contrast(fg, bg);
  if (ratio < 4.5) throw new Error(`${name}: contrast ${ratio.toFixed(2)}:1 is under 4.5:1`);
  contrasts[name] = Math.round(ratio * 10) / 10;
}

const body = `// GENERATED by scripts/tokens.ts from website/app/globals.css (the .dark block) and website/public/logo.svg.
// Do not edit by hand: run \`pnpm tokens\`. \`pnpm tokens:check\` fails if this file is out of date.
export const TOKENS = {
  background: '${hex(background)}',
  card: '${hex(card)}',
  foreground: '${hex(foreground)}',
  primary: '${hex(primary)}',
  mutedForeground: '${hex(mutedForeground)}',
  border: '${hex(border)}',
  radiusPx: ${radiusPx},
  gradient: ['${hex(gradient[0])}', '${hex(gradient[1])}'] as const,
  aurora: ['${hex(aurora[0])}', '${hex(aurora[1])}'] as const,
  auroraOpacity: ${auroraOpacity},
  logoBars: '${fills[0]}',
  logoLine: '${fills[1]}',
} as const;

/** WCAG 2 contrast of every text colour the edit uses on its own fill (each is at least 4.5:1). */
export const CONTRASTS = ${JSON.stringify(contrasts, null, 2)} as const;
`;

if (process.argv.includes('--check')) {
  let disk = '';
  try {
    disk = readFileSync(OUT, 'utf8');
  } catch {
    /* missing */
  }
  if (disk !== body) {
    console.error('src/tokens.generated.ts is out of date: run `pnpm tokens`');
    process.exit(1);
  }
  console.log('tokens ok', contrasts);
} else {
  writeFileSync(OUT, body);
  console.log('wrote', OUT, contrasts);
}
